// Backfills "Key takeaways" for posts that don't have them, in two steps so you can review first.
//
//   node scripts/takeaways.ts            # generate → scripts/takeaways-review.md (+ .cache JSON)
//   node scripts/takeaways.ts --apply    # write the reviewed takeaways into EmDash and publish
//   node scripts/takeaways.ts <slug>…    # only these posts
//
// Edit or delete entries in scripts/.cache/takeaways.json before --apply to change what's written.
// Uses OPENROUTER_API_KEY / OPENROUTER_MODEL from web/.env. Same --url / EMDASH_TOKEN
// options as scripts/import.ts for a deployed site.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EmDashClient } from "emdash/client";
import { formatTakeaways, generateTakeaways, plainText, type Takeaway } from "../src/lib/ai.ts";

const root = join(import.meta.dirname, "..");
const env = Object.fromEntries(
	(existsSync(join(root, ".env")) ? readFileSync(join(root, ".env"), "utf8") : "")
		.split("\n")
		.filter((l) => /^[A-Z_]+=/.test(l))
		.map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim()]),
);
const apiKey = process.env.OPENROUTER_API_KEY ?? env.OPENROUTER_API_KEY;
const model = process.env.OPENROUTER_MODEL ?? env.OPENROUTER_MODEL;

const args = process.argv.slice(2);
const apply = args.includes("--apply");
const urlFlag = args.indexOf("--url");
const baseUrl = urlFlag >= 0 ? args[urlFlag + 1] : "http://localhost:4321";
const only = new Set(args.filter((a, i) => !a.startsWith("--") && args[i - 1] !== "--url"));

const token = process.env.EMDASH_TOKEN;
const client = new EmDashClient(token ? { baseUrl, token } : { baseUrl, devBypass: true });
const api = <T = unknown>(method: string, path: string, body?: unknown): Promise<T> =>
	(client as unknown as { request: (m: string, p: string, b?: unknown) => Promise<T> }).request(method, path, body);

const cacheDir = join(import.meta.dirname, ".cache");
const resultsFile = join(cacheDir, "takeaways.json");
const reviewFile = join(import.meta.dirname, "takeaways-review.md");
mkdirSync(cacheDir, { recursive: true });

type Result = { slug: string; id: string; title: string; takeaways: Takeaway[] };

if (apply) {
	const results: Result[] = JSON.parse(readFileSync(resultsFile, "utf8"));
	let n = 0;
	for (const r of results) {
		if ((only.size && !only.has(r.slug)) || !r.takeaways.length) continue;
		await api("PUT", `/content/posts/${encodeURIComponent(r.id)}`, { data: { key_takeaways: formatTakeaways(r.takeaways) } });
		await client.publish("posts", r.id);
		console.log(`✓ ${r.slug}`);
		n++;
	}
	console.log(`\nWrote takeaways to ${n} posts.`);
	process.exit(0);
}

if (!apiKey) throw new Error("OPENROUTER_API_KEY is not set (web/.env)");

// Every post still missing takeaways
const todo: { id: string; slug: string; title: string; description: string; content: unknown[] }[] = [];
let cursor: string | undefined;
do {
	const page = await client.list("posts", { limit: 100, cursor });
	for (const item of page.items) {
		const slug = item.slug ?? item.id;
		if (only.size && !only.has(slug)) continue;
		if (String(item.data.key_takeaways ?? "").trim()) continue;
		const full = await client.get("posts", item.id, { raw: true });
		todo.push({ id: item.id, slug, title: String(full.data.title), description: String(full.data.description ?? ""), content: (full.data.content as unknown[]) ?? [] });
	}
	cursor = page.nextCursor;
} while (cursor);

console.log(`${todo.length} posts need takeaways (model: ${model ?? "default"})`);
const results: Result[] = [];
const failed: string[] = [];
const queue = [...todo];
// A few at a time: quick, and gentle on rate limits
await Promise.all(
	Array.from({ length: 4 }, async () => {
		for (let p = queue.shift(); p; p = queue.shift()) {
			try {
				const text = plainText(p.content);
				const takeaways = text.length < 400 ? [] : await generateTakeaways({ apiKey, model }, { title: p.title, description: p.description, text });
				results.push({ slug: p.slug, id: p.id, title: p.title, takeaways });
				console.log(`${takeaways.length ? "✓" : "–"} ${p.slug}`);
			} catch (err) {
				failed.push(`${p.slug}: ${err instanceof Error ? err.message : err}`);
				console.error(`✗ ${p.slug}`);
			}
		}
	}),
);

results.sort((a, b) => a.slug.localeCompare(b.slug));
writeFileSync(resultsFile, JSON.stringify(results, null, 2));
writeFileSync(
	reviewFile,
	`# Key takeaways for review\n\nGenerated by \`node scripts/takeaways.ts\`. Edit \`scripts/.cache/takeaways.json\` to change any of these, then run \`node scripts/takeaways.ts --apply\`.\n\n` +
		results
			.map((r) => `## [${r.title}](/blog/${r.slug}/)\n\n${r.takeaways.length ? r.takeaways.map((t) => `- **${t.lead}.** ${t.detail}`).join("\n") : "_Too short; skipped._"}\n`)
			.join("\n") +
		(failed.length ? `\n## Failed\n\n${failed.map((f) => `- ${f}`).join("\n")}\n` : ""),
);
console.log(`\n${results.length} generated, ${failed.length} failed. Review: scripts/takeaways-review.md`);
